# REPO-SPECIFIC: HomeClaw's shots are Mac windows on a gradient with a
# tagline, not device bezels, so framing stays with scripts/frame_screenshots.sh
# (ImageMagick) rather than the frameit port other apps use.
cmd_frame() {
  SRC_DIR="$SHOTS_DIR/$LOCALE" OUT_DIR="$FRAMED_DIR/$LOCALE" "$REPO_ROOT/scripts/frame_screenshots.sh" "$@"
}

# Stages framed PNGs into one directory per App Store display type (by pixel
# size) and replaces each set. --replace deletes the whole existing set first,
# so a partial local set would silently drop screenshots from the listing.
# Every panel (titles in title.strings, or else every raw capture in
# appstore/screenshots) must therefore have a framed shot per display type
# unless --allow-partial is passed.
cmd_upload_screenshots() {
  local dry_run=false allow_partial=false version=""
  while [[ $# -gt 0 ]]; do
    case "$1" in
      --dry-run) dry_run=true ;;
      --allow-partial) allow_partial=true ;;
      --version) version="$2"; shift ;;
      *) die "unknown upload-screenshots option: $1" ;;
    esac
    shift
  done
  load_credentials
  $dry_run && read_only
  version="${version:-$(marketing_version)}"
  [[ -n "$(version_id "$version")" ]] || die "App Store version $version does not exist yet (\`release\` creates it)."
  local src="$FRAMED_DIR/$LOCALE" stage="$ARTIFACTS/screenshots"
  compgen -G "$src/*.png" >/dev/null || die "no framed screenshots in $src (run: scripts/release.sh frame)"

  "$PYTHON" - "$src" "$stage" "$SCREENSHOT_TYPES" "$SHOTS_DIR/$LOCALE" "$allow_partial" <<'PY'
import re, shutil, sys
from pathlib import Path
from PIL import Image
src, stage, types, raw, allow_partial = Path(sys.argv[1]), Path(sys.argv[2]), sys.argv[3], Path(sys.argv[4]), sys.argv[5] == "true"
by_size = dict(t.split("=") for t in types.split())
shutil.rmtree(stage, ignore_errors=True)  # our own staging dir under .asc/
strings = raw / "title.strings"
if strings.exists():
    titles = re.findall(r'^"([^"]+)"\s*=', strings.read_text(), re.M)
else:
    titles = sorted(p.stem for p in raw.glob("*.png"))
found = {}
for png in sorted(src.glob("*.png")):
    w, h = Image.open(png).size
    kind = by_size.get(f"{w}x{h}")
    if not kind:
        sys.exit(f"{png.name}: {w}x{h} matches no display type in SCREENSHOT_TYPES")
    (stage / kind).mkdir(parents=True, exist_ok=True)
    shutil.copy2(png, stage / kind / png.name)
    found.setdefault(kind, []).append(png.name)
missing = []
for kind, names in sorted(found.items()):
    print(f"    {kind}: {len(names)} screenshot(s)")
    for title in titles:
        if not any(title in n for n in names):
            missing.append(f"{kind} {title}")
if missing:
    msg = "missing framed screenshots (the upload replaces the whole set): " + ", ".join(missing)
    if allow_partial:
        print("warning: " + msg, file=sys.stderr)
    else:
        sys.exit(msg + "\nCapture them (see appstore/MANUAL_SCREENSHOTS.md) or pass --allow-partial.")
PY

  local dir kind mode=(--confirm)
  $dry_run && mode=(--dry-run)
  for dir in "$stage"/*/; do
    kind=$(basename "$dir")
    step "Screenshots $kind -> $version $LOCALE ($($dry_run && echo dry run || echo replace))"
    asc screenshots upload --app "$APP_ID" --version "$version" --platform "$PLATFORM" --locale "$LOCALE" \
      --path "$dir" --device-type "$kind" --replace "${mode[@]}" --output table
  done
}

