# Runs a noisy build step with its output in .asc/logs/<name>.log, showing
# the tail only when it fails.
logged() {
  local name="$1" log="$REPO_ROOT/.asc/logs/$1.log"
  shift
  mkdir -p "$(dirname "$log")"
  if ! "$@" >"$log" 2>&1; then
    tail -n 40 "$log" >&2
    die "$name failed. Full log: $log"
  fi
  info "log: .asc/logs/$name.log"
}

archive_only() {
  local container=(--project "$REPO_ROOT/$PROJECT")
  [[ -n "$WORKSPACE" ]] && container=(--workspace "$REPO_ROOT/$WORKSPACE")
  mkdir -p "$ARTIFACTS"

  step "Archive $SCHEME $(marketing_version) ($(build_number))"
  snapshot_version_file
  # -allowProvisioningUpdates + the API key lets the automatic-signing archive
  # step refresh development profiles headlessly. Without the key it depends on
  # an Apple ID session inside Xcode, which silently vanishes on Xcode updates
  # ("No Accounts" / "No signing certificate 'Mac Installer Distribution'").
  # The version pair is passed explicitly for build-settings parity with the
  # Info.plist the pre-build script writes.
  logged archive asc xcode archive "${container[@]}" --scheme "$SCHEME" --configuration Release --clean \
    --archive-path "$ARCHIVE_PATH" --overwrite \
    --xcodebuild-flag=-destination --xcodebuild-flag="$DESTINATION" \
    --xcodebuild-flag="DEVELOPMENT_TEAM=$TEAM_ID" \
    --xcodebuild-flag="MARKETING_VERSION=$(marketing_version)" \
    --xcodebuild-flag="CURRENT_PROJECT_VERSION=$(build_number)" \
    --xcodebuild-flag=ONLY_ACTIVE_ARCH=NO \
    --xcodebuild-flag=-allowProvisioningUpdates \
    --xcodebuild-flag=-authenticationKeyPath --xcodebuild-flag="$ASC_PRIVATE_KEY_PATH" \
    --xcodebuild-flag=-authenticationKeyID --xcodebuild-flag="$ASC_KEY_ID" \
    --xcodebuild-flag=-authenticationKeyIssuerID --xcodebuild-flag="$ASC_ISSUER_ID" \
    --output json
  restore_version_file
  info "$ARCHIVE_PATH"
  verify_archive_contents
}

archive_and_export() {
  archive_only

  step "Export $PACKAGE_LABEL (manual signing, App Store profiles)"
  # If export fails, the useful log is the .xcdistributionlogs bundle path
  # printed by xcodebuild (IDEDistribution.standard.log), not the summary.
  logged export asc xcode export --archive-path "$ARCHIVE_PATH" "--$PACKAGE_KIND-path" "$PACKAGE_PATH" \
    --export-options "$EXPORT_OPTIONS" --overwrite --output json
  info "$PACKAGE_PATH"

  # The restore above must leave the tree exactly as committed.
  local after
  after=$(git -C "$REPO_ROOT" status --porcelain)
  [[ -z "$after" ]] || die "the build left the worktree dirty:
$after"
}

# REPO-SPECIFIC: sanity-check the archive's bundle structure (was the old
# Fastfile's verify_bundle!), then that the binary carries the committed
# version pair.
verify_archive_contents() {
  local app="$ARCHIVE_PATH/Products/Applications/$APP_NAME.app" rel missing=()
  for rel in Contents/MacOS/HomeClaw Contents/MacOS/homeclaw-cli Contents/Resources/mcp-server.js \
    Contents/Resources/openclaw/dist/index.js; do
    [[ -f "$app/$rel" ]] || missing+=("$rel")
  done
  for rel in Contents/Resources/macOSBridge.bundle Contents/Resources/openclaw; do
    [[ -d "$app/$rel" ]] || missing+=("$rel")
  done
  [[ ${#missing[@]} -eq 0 ]] || die "archive is missing: ${missing[*]}"
  info "Bundle has HomeClaw, homeclaw-cli, macOSBridge.bundle, mcp-server.js, openclaw/"

  # Without it HMHomeManager silently returns zero homes.
  codesign -d --entitlements :- "$app" 2>/dev/null | grep -q "com.apple.developer.homekit" \
    || die "HomeKit entitlement missing on the signed app."
  # Build 154 was rejected by App Store Connect with error 90296 ("App sandbox
  # not enabled") on homeclaw-cli: every executable in a Mac App Store bundle
  # must be sandboxed.
  codesign -d --entitlements :- "$app/Contents/MacOS/homeclaw-cli" 2>/dev/null \
    | grep -q "com.apple.security.app-sandbox" \
    || die "homeclaw-cli is not sandboxed; App Store Connect rejects the upload (error 90296)."
  info "HomeKit entitlement present; homeclaw-cli sandboxed"

  local plist="$app/Contents/Info.plist" built_version built_build
  built_version=$(/usr/libexec/PlistBuddy -c "Print :CFBundleShortVersionString" "$plist")
  built_build=$(/usr/libexec/PlistBuddy -c "Print :CFBundleVersion" "$plist")
  [[ "$built_version" == "$(marketing_version)" && "$built_build" == "$(build_number)" ]] \
    || die "archive is $built_version ($built_build) but HEAD says $(marketing_version) ($(build_number))."
  info "Archived binary is $built_version ($built_build)"
}

validate_package() {
  step "Validate $PACKAGE_LABEL with Apple (altool --validate-app, no upload)"
  # altool finds AuthKey_<id>.p8 via API_PRIVATE_KEYS_DIR.
  API_PRIVATE_KEYS_DIR="$(dirname "$ASC_PRIVATE_KEY_PATH")" \
