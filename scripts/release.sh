# App Store version id for a version string ("" when it doesn't exist yet).
version_id() {
  asc versions list --app "$APP_ID" --platform "$PLATFORM" --version "$1" --output json \
    | json_get 'd["data"][0]["id"] if d.get("data") else None'
}

version_state() {
  asc versions list --app "$APP_ID" --platform "$PLATFORM" --version "$1" --output json \
    | json_get '(d["data"][0]["attributes"].get("appStoreState") or d["data"][0]["attributes"].get("appVersionState")) if d.get("data") else None'
}

# Newest version still being prepared, else the live one: deliver's own
# precedence (use_live_version: false). See metadata-pull.
editable_or_live_version_id() {
  local prefer_live="$1"
  asc versions list --app "$APP_ID" --platform "$PLATFORM" --paginate --output json | "$PYTHON" -c '
import json, sys
prefer_live = sys.argv[1] == "true"
d = json.load(sys.stdin)["data"]
d.sort(key=lambda v: v["attributes"].get("createdDate") or "", reverse=True)
state = lambda v: v["attributes"].get("appStoreState") or v["attributes"].get("appVersionState") or ""
live = [v for v in d if state(v) == "READY_FOR_SALE"][:1]
edit = [v for v in d if state(v) not in ("READY_FOR_SALE", "REMOVED_FROM_SALE", "DEVELOPER_REMOVED_FROM_SALE", "REPLACED_WITH_NEW_VERSION")][:1]
pick = (live or edit) if prefer_live else (edit or live)
if pick:
    print(pick[0]["id"], pick[0]["attributes"]["versionString"], state(pick[0]))
' "$prefer_live"
}

# "<build id> <build number> <usesNonExemptEncryption>" for a version.
find_build() {
  local version="$1" number="${2:-}" args=()
  [[ -n "$number" ]] && args=(--build-number "$number")
  asc builds list --app "$APP_ID" --platform "$PLATFORM" --version "$version" \
    --processing-state VALID --sort -uploadedDate --limit 1 ${args[@]+"${args[@]}"} --output json \
    | json_get '" ".join(str(x) for x in (d["data"][0]["id"], d["data"][0]["attributes"]["version"], d["data"][0]["attributes"].get("usesNonExemptEncryption"))) if d.get("data") else None'
}

