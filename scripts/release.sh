# REPO-SPECIFIC: the old lanes computed the next build as `.build-number` + 1
# at archive time and committed the bumped Info.plist after the upload. The
# number now lands in a commit first: next = one past the highest of the
# committed plist, the local `.build-number` counter, and (when credentials
# are available) App Store Connect's highest uploaded build.
cmd_bump_build() {
  local current counter remote="" next version
  current=$(build_number)
  counter=$(tr -d '[:space:]' <"$REPO_ROOT/.build-number" 2>/dev/null || echo 0)
  next=$(( current > counter ? current : counter ))
  if (load_credentials) >/dev/null 2>&1; then
    load_credentials
    read_only
    remote=$(asc builds next-build-number --app "$APP_ID" --platform "$PLATFORM" --output json \
      | json_get 'd.get("latestObservedBuildNumber")' || true)
    [[ -n "$remote" && "$remote" -gt "$next" ]] && next="$remote"
  else
    warn "no App Store Connect credentials; not checking uploaded build numbers."
  fi
  next=$((next + 1))
  version=$(marketing_version)
  /usr/libexec/PlistBuddy -c "Set :CFBundleVersion $next" -c "Set :CFBundleShortVersionString $version" "$REPO_ROOT/$INFO_PLIST"
  bold "$INFO_PLIST -> $version ($next)"
  info "plist was $current, .build-number $counter, App Store Connect highest ${remote:-unknown}"
  info "Next: git commit -m \"chore(release): build $next\" $INFO_PLIST"
  info "      git tag -a v$version+$next -m \"Release v$version build $next\" && git push && git push origin v$version+$next"
}

