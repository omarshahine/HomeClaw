warn() { printf '\033[33mwarning:\033[0m %s\n' "$*" >&2; }
die() { printf '\033[31merror:\033[0m %s\n' "$*" >&2; exit 1; }

# json_get '<python expression over d>' < json — tiny jq substitute that
# ships with macOS. Prints nothing (not "None") for a missing value.
json_get() {
  "$PYTHON" -c 'import json,sys
d=json.load(sys.stdin)
v=eval(sys.argv[1])
print("" if v is None else v)' "$1"
}

# ─── Credentials ─────────────────────────────────────────────────────────
#
# asc reads ASC_KEY_ID / ASC_ISSUER_ID / ASC_PRIVATE_KEY_PATH. An interactive
# shell already has them from ~/.zshrc; otherwise fall back to the chezmoi
# secrets file (canonical APP_STORE_CONNECT_API_* names) and then the repo's
# .env.local (per-project ASC_* / *_TEAM_ID overrides). Values are never
# printed. The macOS Keychain is never used (ASC_BYPASS_KEYCHAIN=1).
load_credentials() {
  if [[ -z "${ASC_KEY_ID:-}" ]]; then
    local secrets="$HOME/.secrets-macbook-pro.env"
    # shellcheck source=/dev/null
    [[ -f "$secrets" ]] && source "$secrets"
    # shellcheck source=/dev/null
    [[ -f "$REPO_ROOT/.env.local" ]] && source "$REPO_ROOT/.env.local"
    ASC_KEY_ID="${ASC_KEY_ID:-${APP_STORE_CONNECT_API_KEY_ID:-}}"
    ASC_ISSUER_ID="${ASC_ISSUER_ID:-${APP_STORE_CONNECT_API_ISSUER_ID:-}}"
  fi
  if [[ -z "${ASC_PRIVATE_KEY_PATH:-}" ]]; then
    # ASC_KEY_PATH is the name the old Fastfile/.env.local used.
    if [[ -n "${ASC_KEY_PATH:-}" ]]; then
      ASC_PRIVATE_KEY_PATH="$ASC_KEY_PATH"
    elif [[ -f "$HOME/.private_keys/AuthKey_${ASC_KEY_ID:-}.p8" ]]; then
      ASC_PRIVATE_KEY_PATH="$HOME/.private_keys/AuthKey_${ASC_KEY_ID}.p8"
    elif [[ "${ASC_KEY_ID:-}" == "${APP_STORE_CONNECT_API_KEY_ID:-}" ]]; then
      ASC_PRIVATE_KEY_PATH="${APP_STORE_CONNECT_API_KEY_PATH:-}"
    fi
  fi
  [[ -n "${ASC_KEY_ID:-}" && -n "${ASC_ISSUER_ID:-}" ]] \
    || die "App Store Connect API key not configured (ASC_KEY_ID/ASC_ISSUER_ID or APP_STORE_CONNECT_API_KEY_ID/_ISSUER_ID)."
  [[ -f "${ASC_PRIVATE_KEY_PATH:-}" ]] || die "App Store Connect .p8 key not found (set ASC_PRIVATE_KEY_PATH)."
  export ASC_KEY_ID ASC_ISSUER_ID ASC_PRIVATE_KEY_PATH
  export ASC_BYPASS_KEYCHAIN=1 ASC_TELEMETRY_DISABLED=1

  # The repo's .env.local carries its own *_TEAM_ID. When ~/.zshrc already
  # exported the ASC_* key it isn't sourced above, so read only the team-id
  # names from it in a subshell; the key pairing exported above stays intact.
  TEAM_ID="" TEAM_ID_SOURCE=""
  local var value
  for var in $TEAM_ID_VARS; do
    value="${!var:-}"
    if [[ -z "$value" && -f "$REPO_ROOT/.env.local" ]]; then
      # shellcheck source=/dev/null
      value=$(source "$REPO_ROOT/.env.local" >/dev/null 2>&1; printf '%s' "${!var:-}")
    fi
    # .env.local.example ships HOMEKIT_TEAM_ID=YOUR_TEAM_ID; that is unset.
    [[ "$value" == "YOUR_TEAM_ID" ]] && value=""
    if [[ -n "$value" ]]; then TEAM_ID="$value" TEAM_ID_SOURCE="$var"; break; fi
  done
}

# Every read-only or --dry-run path runs with ASC_READ_ONLY=1, so asc refuses
# any POST/PATCH/PUT/DELETE before it is sent, even if a flag is wrong here.
read_only() { export ASC_READ_ONLY=1; }

# ─── Project facts ───────────────────────────────────────────────────────

plist_value() { /usr/libexec/PlistBuddy -c "Print :$1" "$REPO_ROOT/$INFO_PLIST"; }

# REPO-SPECIFIC: HomeClaw's marketing version comes from the nearest `v*` git
# tag, not the project: release tags are `v{version}+{build}` and Apple
# rejects the extra component, so the `+build` suffix is stripped. project.yml's
# archive pre-build script derives CFBundleShortVersionString the same way, so
# a new version starts with `git tag -a v1.0.13` (scripts/bump-version.sh).
marketing_version() {
  local tag
  tag=$(git -C "$REPO_ROOT" describe --tags --abbrev=0 --match 'v*' 2>/dev/null || true)
  tag="${tag:-v0.0.1}"
  tag="${tag#v}"
  printf '%s\n' "${tag%%+*}"
}

# REPO-SPECIFIC: the build number is CFBundleVersion as committed in
# Resources/Info.plist. `bump-build` writes the next one; commit it
# ("chore(release): build N") and tag v{version}+N before `beta`.
build_number() { plist_value CFBundleVersion; }

# TestFlight "What to Test" defaults to the App Store release notes so it
