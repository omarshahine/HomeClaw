# REPO-SPECIFIC (from the old Fastfile's profile resolver): a profile minted on
# another Mac embeds that machine's distribution certificate. Exporting with it
# fails on a certificate mismatch, so require that one of the profile's
# embedded certificates is installed here. DeveloperCertificates holds DER
# blobs whose SHA-1 is the fingerprint `security find-identity` prints (this
# lists identities; it reads no secrets).
require_profile_certificate() {
  local file="$1" name="$2" local_ids
  local_ids=$(security find-identity -v -p codesigning | grep -oE '\b[0-9A-F]{40}\b' | sort -u)
  security cms -D -i "$file" | "$PYTHON" -c '
import hashlib, plistlib, sys
local = set(sys.argv[1].split())
certs = plistlib.loads(sys.stdin.buffer.read()).get("DeveloperCertificates", [])
sys.exit(0 if any(hashlib.sha1(c).hexdigest().upper() in local for c in certs) else 1)
' "$local_ids" || die "profile '$name' is signed for a certificate that is not in this keychain. Regenerate it for this Mac's Apple Distribution certificate."
}

