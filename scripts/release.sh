# ASC's current metadata for one version, written in the same fastlane layout
# as appstore/metadata. `asc migrate export` covers the localized .txt files;
# copyright and categories are read separately because migrate skips them.
export_remote_metadata() {
  local vid="$1" dir="$2" category
  asc migrate export --app "$APP_ID" --version-id "$vid" --output-dir "$dir" --output json >/dev/null
  mkdir -p "$dir/metadata"
  asc versions list --app "$APP_ID" --platform "$PLATFORM" --paginate --output json \
    | json_get 'next((v["attributes"].get("copyright") for v in d["data"] if v["id"] == "'"$vid"'"), None)' \
    >"$dir/metadata/copyright.txt"
  for category in primary secondary; do
    asc apps info relationships "$category-category" --app "$APP_ID" --output json \
      | json_get 'd["data"].get("id") or None' >"$dir/metadata/${category}_category.txt"
    # An unset category comes back empty; don't invent an empty file for it.
    [[ -s "$dir/metadata/${category}_category.txt" && -n "$(tr -d '[:space:]' <"$dir/metadata/${category}_category.txt")" ]] \
      || mv -f "$dir/metadata/${category}_category.txt" "$dir/.unset-${category}_category.txt"
  done
}

# Unified diff of a local metadata tree against ASC (remote), ignoring
# trailing whitespace. Returns 0 when they match. A partial tree (--notes-only)
# is compared file by file, so absent files don't read as deletions.
diff_metadata() {
  local vid="$1" local_dir="$2" tmp changes
  mkdir -p "$ARTIFACTS"
  tmp=$(mktemp -d "$ARTIFACTS/metadata-diff.XXXXXX")
  export_remote_metadata "$vid" "$tmp"
  # A push only uploads the files it has, so a file only on ASC is no change.
  changes=$(cd "$tmp" && diff -ru -b metadata "$local_dir" | grep -v '^Only in metadata' || true)
  if [[ -z "$changes" ]]; then
    info "$(basename "$(dirname "$local_dir")")/metadata matches App Store Connect (no changes to push)"
    return 0
  fi
  info "Changes a push would make (--- ASC, +++ local):"
  printf '%s\n' "$changes" | sed 's/^/      /'
  return 1
}

# Pushes a metadata tree (fastlane layout, default appstore/metadata) to one
# App Store version. Every .txt is uploaded: description, keywords, name,
# subtitle, URLs, release notes, review information, copyright, categories.
# Run metadata-pull first if ASC may have drifted. A dry run shows the file
# list asc would import and the diff against ASC.
push_metadata() {
  local vid="$1" dry_run="$2" root="${3:-$APPSTORE_DIR}"
  local meta="$root/metadata"
  if $dry_run; then
    asc migrate import --app "$APP_ID" --version-id "$vid" --fastlane-dir "$root" \
      --skip-screenshots --skip-previews --dry-run --output table
    diff_metadata "$vid" "$meta" || true
    return
  fi
  asc migrate import --app "$APP_ID" --version-id "$vid" --fastlane-dir "$root" \
    --skip-screenshots --skip-previews --confirm --output table
  if [[ -f "$meta/copyright.txt" ]]; then
    asc versions update --version-id "$vid" --copyright "$(tr -d '\n' <"$meta/copyright.txt")" --output json >/dev/null
    info "copyright.txt pushed"
  fi
  if [[ -f "$meta/primary_category.txt" ]]; then
    local args=(--primary "$(tr -d '[:space:]' <"$meta/primary_category.txt")")
    [[ -f "$meta/secondary_category.txt" ]] \
      && args+=(--secondary "$(tr -d '[:space:]' <"$meta/secondary_category.txt")")
    asc categories set --app "$APP_ID" "${args[@]}" --output json >/dev/null
    info "categories pushed"
  fi
}

cmd_metadata() {
  local dry_run=false version=""
  while [[ $# -gt 0 ]]; do
    case "$1" in
      --dry-run) dry_run=true ;;
      --version) version="$2"; shift ;;
      *) die "unknown metadata option: $1" ;;
    esac
    shift
  done
  load_credentials
