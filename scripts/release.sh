}

# `appstore/metadata/` is the version-controlled source of truth that
# `release` pushes. This pulls the other direction: it overwrites the local
# files with what ASC currently holds, so a hand-edit made in the web UI lands
# as a reviewable diff instead of silently drifting.
#
# Edit-first, matching deliver's own default (use_live_version: false). While
# a version is being prepared, the edits worth capturing live on that upcoming
# version; reading the live listing instead would overwrite them with the
# already-shipped copy, and the next `release` would push that stale text back
# over the new version. --live deliberately reads the shipped listing.
cmd_metadata_pull() {
  local live=false
  while [[ $# -gt 0 ]]; do
    case "$1" in
      --live) live=true ;;
      *) die "unknown metadata-pull option: $1" ;;
    esac
    shift
  done
  load_credentials
  read_only
  local picked vid version state tmp
  picked=$(editable_or_live_version_id "$live")
  [[ -n "$picked" ]] || die "no editable or live App Store version."
  read -r vid version state <<<"$picked"
  step "Reading App Store version $version ($state)"
  mkdir -p "$ARTIFACTS"
  tmp=$(mktemp -d "$ARTIFACTS/metadata-pull.XXXXXX")
  export_remote_metadata "$vid" "$tmp"
  mkdir -p "$METADATA_DIR"
  rsync -a "$tmp/metadata/" "$METADATA_DIR/"
  info "Synced -> $METADATA_DIR"
  warn "review \`git diff appstore/metadata\` before committing."
}

# Shared by release and submit. deliver's submission_information answered the
# export-compliance question on every submission; the Info.plist carries
# ITSAppUsesNonExemptEncryption=NO, so builds normally arrive answered and
# this only fills a gap.
ensure_encryption_answer() {
  local build_id="$1" answer="$2" dry_run="$3"
  if [[ "$answer" == "False" || "$answer" == "false" ]]; then
    info "Export compliance: already answered (no non-exempt encryption)"
  elif $dry_run; then
    info "Would set usesNonExemptEncryption=false on build $build_id"
  else
    asc builds update --build-id "$build_id" --uses-non-exempt-encryption=false --output json >/dev/null
    info "Export compliance: set usesNonExemptEncryption=false"
  fi
}

# REPO-SPECIFIC release options (the old `release` / `release_build` lanes).
RELEASE_NOTES=""          # --notes-file / --notes: "What's New" for this submission
RELEASE_NOTES_ONLY=false  # --notes-only: push only "What's New" (was skip_metadata:true)
RELEASE_SCREENSHOTS=false # release replaces the screenshot set unless --skip-screenshots

# The metadata tree a release pushes. Default: appstore itself. With notes
# given, a staged copy whose en-US/release_notes.txt carries them. With
# --notes-only, a tree holding just that file: the importer only uploads
# fields whose files exist, so every other field on the live listing is left
# alone (deliver's skip_metadata:true would have dropped "What's New" too).
release_metadata_root() {
  if [[ -z "$RELEASE_NOTES" ]] && ! $RELEASE_NOTES_ONLY; then
    printf '%s\n' "$APPSTORE_DIR"
    return
  fi
  local root
  mkdir -p "$ARTIFACTS"
  root=$(mktemp -d "$ARTIFACTS/release-metadata.XXXXXX")
  mkdir -p "$root/metadata/$LOCALE"
  $RELEASE_NOTES_ONLY || rsync -a "$METADATA_DIR/" "$root/metadata/"
  if [[ -n "$RELEASE_NOTES" ]]; then
    printf '%s\n' "$RELEASE_NOTES" >"$root/metadata/$LOCALE/release_notes.txt"
  else
    cp "$METADATA_DIR/$LOCALE/release_notes.txt" "$root/metadata/$LOCALE/release_notes.txt"
  fi
  printf '%s\n' "$root"
}

submit_for_review() {
  local version="$1" build="$2" dry_run="$3" push="$4"
  local vid state found build_id build_num answer
  vid=$(version_id "$version")

  step "App Store version $version"
  if [[ -n "$vid" ]]; then
    state=$(version_state "$version")
    info "Version $version is $state"
    # asc's own dry run doesn't look at state. A live or in-review version
    # can't take metadata edits or a new submission, so stop before sending
    # anything.
    case "$state" in
      READY_FOR_SALE | READY_FOR_DISTRIBUTION | WAITING_FOR_REVIEW | IN_REVIEW | PENDING_DEVELOPER_RELEASE)
        if $dry_run; then
          warn "$version is $state; a real run would refuse. Tag the next version (v<X.Y.Z>) for the next release."
        else
          die "$version is $state and can't be submitted again. Tag the next version (v<X.Y.Z>) for the next release."
        fi
        ;;
    esac
    if $push; then
      if $dry_run; then
        info "Would set release type $RELEASE_TYPE"
      else
        asc versions update --version-id "$vid" --release-type "$RELEASE_TYPE" --output json >/dev/null
        info "Release type $RELEASE_TYPE"
      fi
    fi
  elif ! $push; then
    die "App Store version $version does not exist (\`release\` creates it)."
  elif $dry_run; then
    info "Would create App Store version $version (release type $RELEASE_TYPE)"
  else
    asc versions create --app "$APP_ID" --version "$version" --platform "$PLATFORM" \
      --release-type "$RELEASE_TYPE" --if-exists skip --output json >/dev/null
    vid=$(version_id "$version")
    info "Created version $version"
  fi

  if $push; then
    step "Metadata -> $version"
    local root
    root=$(release_metadata_root)
    [[ -n "$(tr -d '[:space:]' <"$root/metadata/$LOCALE/release_notes.txt" 2>/dev/null)" ]] \
      || die "missing \"What's New\": $root/metadata/$LOCALE/release_notes.txt is empty (or pass --notes-file / --notes)."
    if [[ -n "$vid" ]]; then
      push_metadata "$vid" "$dry_run" "$root"
    else
      info "Would push $root/metadata once the version exists"
    fi
    if $RELEASE_SCREENSHOTS; then
      if [[ -n "$vid" ]]; then
        local mode=()
        $dry_run && mode=(--dry-run)
        cmd_upload_screenshots --version "$version" ${mode[@]+"${mode[@]}"}
      else
        info "Would replace the screenshot sets from appstore/framed once the version exists"
      fi
    fi
  fi

  step "Build"
  found=$(find_build "$version" "$build")
  [[ -n "$found" ]] || die "no VALID build${build:+ $build} for version $version on App Store Connect."
  read -r build_id build_num answer <<<"$found"
  info "Build $build_num ($build_id)"
  ensure_encryption_answer "$build_id" "$answer" "$dry_run"

  step "Submit $version ($build_num) for App Review"
  if [[ -z "$vid" ]]; then
    info "Would attach build $build_num and submit (version not created in a dry run)"
  elif $dry_run; then
    asc review submit --app "$APP_ID" --version-id "$vid" --build-id "$build_id" --platform "$PLATFORM" --dry-run --output json
    echo
  else
    asc review submit --app "$APP_ID" --version-id "$vid" --build-id "$build_id" --platform "$PLATFORM" --confirm --output json
    echo
    if [[ "$RELEASE_TYPE" == "MANUAL" ]]; then
      bold "Submitted $version ($build_num) for App Review; after approval it waits in Pending Developer Release."
    else
      bold "Submitted $version ($build_num) for App Review; releases automatically after approval."
    fi
    info "Track at https://appstoreconnect.apple.com/apps/$APP_ID/distribution"
  fi
}

parse_submit_args() {
  SUBMIT_DRY_RUN=false SUBMIT_VERSION="" SUBMIT_BUILD=""
  while [[ $# -gt 0 ]]; do
    case "$1" in
      --dry-run) SUBMIT_DRY_RUN=true ;;
      --version) SUBMIT_VERSION="$2"; shift ;;
      --build) SUBMIT_BUILD="$2"; shift ;;
      # REPO-SPECIFIC (release only; see cmd_release).
      --notes) RELEASE_NOTES="$2"; shift ;;
      --notes-file) [[ -f "$2" ]] || die "notes file not found: $2"; RELEASE_NOTES="$(<"$2")"; shift ;;
      --notes-only) RELEASE_NOTES_ONLY=true ;;
      --skip-screenshots) RELEASE_SCREENSHOTS=false ;;
      --auto-release) RELEASE_TYPE="AFTER_APPROVAL" ;;
      *) die "unknown option: $1" ;;
    esac
    shift
  done
}

# The old `release` lane built, uploaded and submitted in one go; that is now
# `beta` then `release`. The old `release_build` lane is `release --build N`.
# Both old lanes replaced the screenshot set by default, so this does too
# (--skip-screenshots when appstore/framed is stale relative to the build).
cmd_release() {
  RELEASE_SCREENSHOTS=true
  parse_submit_args "$@"
  load_credentials
  $SUBMIT_DRY_RUN && read_only
  submit_for_review "${SUBMIT_VERSION:-$(marketing_version)}" "$SUBMIT_BUILD" "$SUBMIT_DRY_RUN" true
}

cmd_submit() {
  parse_submit_args "$@"
  if [[ -n "$RELEASE_NOTES" ]] || $RELEASE_NOTES_ONLY; then
    die "submit pushes no metadata; use release --notes-only."
  fi
  load_credentials
  $SUBMIT_DRY_RUN && read_only
  submit_for_review "${SUBMIT_VERSION:-$(marketing_version)}" "$SUBMIT_BUILD" "$SUBMIT_DRY_RUN" false
}

