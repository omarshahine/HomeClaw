}

# ─── Guardrails ──────────────────────────────────────────────────────────

# A release artifact has to be reproducible from a committed revision.
# Build 20 of SendTimes 1.1 reached TestFlight from a dirty tree and no commit
# anywhere carried that build number, so the uploaded binary could never be
# tied back to a source revision. HomeClaw's old lanes archived first and
# committed the bumped Info.plist afterwards, which had the same gap.
require_clean_tree() {
  local dirty
  # A failed `git` would otherwise return "" and read as a clean tree.
  dirty=$(git -C "$REPO_ROOT" status --porcelain) \
    || die "could not read worktree state (git exited $?); refusing to build."
  if [[ -n "$dirty" ]]; then
    printf '%s\n' "$dirty" >&2
    die "worktree is dirty. Commit or stash before cutting a release build."
  fi
}

# REPO-SPECIFIC: resolve the Xcode to archive with, and say which one it was.
#
# A machine with several Xcodes installed otherwise archives against whatever
# `xcode-select` points at, invisibly — a release built on the wrong toolchain
# is not something to discover from App Store Connect. Resolution order:
# DEVELOPER_DIR, XCODE_APP, .xcode-version, xcode-select. Betas and release
# builds live side by side, so .xcode-version is matched on
# CFBundleShortVersionString, not the app name.
resolve_toolchain() {
  local pin="" app installed=() version
  [[ -f "$REPO_ROOT/.xcode-version" ]] && pin=$(tr -d '[:space:]' <"$REPO_ROOT/.xcode-version")
  if [[ -z "${DEVELOPER_DIR:-}" && -n "${XCODE_APP:-}" ]]; then
    DEVELOPER_DIR="$XCODE_APP/Contents/Developer"
  fi
  if [[ -z "${DEVELOPER_DIR:-}" && -n "$pin" ]]; then
    for app in /Applications/Xcode*.app; do
      version=$(defaults read "$app/Contents/Info.plist" CFBundleShortVersionString 2>/dev/null || echo '?')
      installed+=("$app ($version)")
      if [[ "$version" == "$pin" ]]; then DEVELOPER_DIR="$app/Contents/Developer"; break; fi
    done
    [[ -n "${DEVELOPER_DIR:-}" ]] || die ".xcode-version pins Xcode $pin, but no installed Xcode reports that version.
Installed: ${installed[*]}
Install it, or override for this run: XCODE_APP=/Applications/Xcode.app scripts/release.sh <command>"
  fi
  if [[ -n "${DEVELOPER_DIR:-}" ]]; then
    [[ -d "$DEVELOPER_DIR" ]] || die "DEVELOPER_DIR does not exist: $DEVELOPER_DIR"
    export DEVELOPER_DIR
  fi
  version=$(xcodebuild -version | head -n 1)
  info "Toolchain: $version ($(xcode-select -p))"
  [[ -z "$pin" || "$version" == *"$pin"* ]] || warn "toolchain $version does not match .xcode-version pin $pin"
}

# App Review rejects binaries built with a beta Xcode ("The build's Xcode build
# is not supported yet"), but only at submission time: the upload and
# TestFlight processing both succeed, so the build looks fine until it
# silently cannot be submitted. Build 23 of SendTimes 1.1 was lost this way
# when xcode-select pointed at Xcode-beta 27.0. `xcode-select -p` honors
# DEVELOPER_DIR, so a per-invocation override works:
#   DEVELOPER_DIR=/Applications/Xcode.app/Contents/Developer scripts/release.sh beta
require_release_xcode() {
  local developer_dir version build
  developer_dir=$(xcode-select -p)
  version=$(xcodebuild -version | head -n 1)
  build=$(xcodebuild -version | sed -n 's/^Build version //p')
  # Only the app path is a reliable signal: GA build numbers also end in a
  # letter (16A242d) and some GA builds use beta-style numbers (16C5032a).
  if [[ "$developer_dir" == *Xcode-beta* ]]; then
    die "the active Xcode is a beta ($developer_dir, $version, $build).
App Review will not accept a build made with it. Switch with:
  sudo xcode-select -s /Applications/Xcode.app/Contents/Developer
or set DEVELOPER_DIR (or .xcode-version) for this invocation."
  fi
  info "Building with $version ($build) at $developer_dir"
}

# REPO-SPECIFIC: concurrent xcodebuild runs against the same project can wedge
# the build service: a run sits at the toolchain probe producing nothing, which
# reads as a broken toolchain rather than contention. Fail fast instead of
# hanging a release. Scoped to this project; unrelated builds are allowed.
ensure_no_concurrent_build() {
  local pids
  pids=$(pgrep -f "xcodebuild.*$APP_NAME.xcodeproj" 2>/dev/null || true)
  [[ -z "$pids" ]] || die "another xcodebuild is already running against $APP_NAME.xcodeproj (pid ${pids%%$'\n'*}). Concurrent builds wedge the build service. Wait for it to finish, or kill it."
}

# Release integrity: tag before you upload (see AGENTS.md). The build-bump
# commit carries a vX.Y[.Z] or vX.Y[.Z]+BUILD tag, HEAD is that commit, and it
# is pushed. A tag is the only record of which source a shipped binary came
# from. With --dry-run a failure is reported, not fatal, so the build path can
# still be verified from an untagged commit.
check_release_tag() {
  local soft="$1" version build tag tag_version tag_build problems=()
  version=$(marketing_version)
  build=$(build_number)
  # Prefer a vX.Y.Z+BUILD tag when HEAD carries several.
  tag=$(git -C "$REPO_ROOT" tag --points-at HEAD --list 'v*' | sort -t+ -k2 -n | tail -n 1)
  if [[ -z "$tag" ]]; then
    problems+=("HEAD has no v* release tag. Tag the build-bump commit (v$version+$build) before uploading.")
  elif [[ ! "$tag" =~ ^v([0-9]+\.[0-9]+(\.[0-9]+)?)(\+([0-9]+))?$ ]]; then
    problems+=("tag '$tag' is not vX.Y.Z or vX.Y.Z+BUILD.")
  else
    tag_version="${BASH_REMATCH[1]}"
    tag_build="${BASH_REMATCH[4]}"
    [[ "$tag_version" == "$version" ]] \
      || problems+=("tag $tag says version $tag_version but the project says $version.")
    [[ -z "$tag_build" || "$tag_build" == "$build" ]] \
      || problems+=("tag $tag says build $tag_build but the project says $build.")
  fi
  # REPO-SPECIFIC: the archive pre-build script rewrites Info.plist's short
  # version from the tag. If the committed plist disagrees, the archive dirties
  # the tree with a version no commit carries (`bump-build` syncs both).
  local plist_version
  plist_version=$(plist_value CFBundleShortVersionString)
  [[ "$plist_version" == "$version" ]] \
    || problems+=("$INFO_PLIST says version $plist_version but the nearest tag says $version. Run: scripts/release.sh bump-build")
  if [[ -z "$(git -C "$REPO_ROOT" branch -r --contains HEAD 2>/dev/null)" ]]; then
    problems+=("HEAD is not on any remote branch. Push the release commit before uploading.")
  fi
  local p
  for p in ${problems[@]+"${problems[@]}"}; do
    if [[ "$soft" == "soft" ]]; then warn "upload would refuse: $p"; else die "$p"; fi
  done
  [[ ${#problems[@]} -gt 0 ]] || info "Release tag $tag matches $version ($build) and HEAD is pushed"
}

# REPO-SPECIFIC: the build-number write-back.
#
# In SendTimes, Xcode 26+ bumps CURRENT_PROJECT_VERSION in project.pbxproj as
# a side effect of `archive`. HomeClaw's project is generated and gitignored;
# here the writer is project.yml's "Increment Build Number (Archive Only)"
# pre-build script, which sets CFBundleVersion in Resources/Info.plist to
# `.build-number` + 1 (and CFBundleShortVersionString from the tag). Seeding
# `.build-number` with the committed build minus one makes that script land on
# the committed number, so the archive is built with exactly what HEAD says.
# The plist is still snapshotted and put back on success AND failure: the
# archive can succeed and the export then fail (stale profiles, the Homebrew
# rsync issue above), which is exactly how an unbuilt build number used to be
# left behind. Restoring the whole file is safe because beta refuses to start
# against a dirty tree, so any difference is the build's own edit.
VERSION_FILE="$REPO_ROOT/$INFO_PLIST"
VERSION_SNAPSHOT="$ARTIFACTS/Info.plist.before-archive"
SNAPSHOT_ACTIVE=false
snapshot_version_file() {
  cp "$VERSION_FILE" "$VERSION_SNAPSHOT"
  SNAPSHOT_ACTIVE=true
  trap restore_version_file EXIT
  printf '%s\n' "$(($(build_number) - 1))" >"$REPO_ROOT/.build-number"
}
restore_version_file() {
  $SNAPSHOT_ACTIVE || return 0
  SNAPSHOT_ACTIVE=false
  if ! cmp -s "$VERSION_SNAPSHOT" "$VERSION_FILE"; then
    cp "$VERSION_SNAPSHOT" "$VERSION_FILE"
    info "Reverted the archive's edit to $INFO_PLIST; it still reads the build that was archived."
  fi
}

# REPO-SPECIFIC: pre-archive prep. Regenerate the Xcode project and build the
# Node.js MCP server that gets bundled into the app.
prepare() {
  command -v xcodegen >/dev/null || die "xcodegen not installed. brew install xcodegen"
  ensure_no_concurrent_build

  step "Generate Xcode project"
  logged xcodegen xcodegen generate --use-cache --spec "$REPO_ROOT/project.yml" --project "$REPO_ROOT"

  # npm ci, not the existing node_modules: a stale install silently bundles
  # different dependency versions into the shipped mcp-server.js (build 196
  # shipped MCP SDK 1.27.1 against a 1.30.0 lockfile).
  step "Install locked npm dependencies and build the MCP server"
  logged npm-ci npm ci --no-audit --no-fund
  logged build-mcp npm run build:mcp

  # The bundle goes into the app, so it must match the committed source.
  local dist="mcp-server/dist/server.js"
  git -C "$REPO_ROOT" diff --quiet HEAD -- "$dist" \
    || die "$dist differs from the committed bundle after a clean build. Commit the rebuilt bundle (via PR) before releasing."

  # Without the HomeKit entitlement HMHomeManager silently returns zero homes.
  grep -q "com.apple.developer.homekit" "$REPO_ROOT/Resources/HomeClaw.entitlements" \
    || die "HomeKit entitlement missing from Resources/HomeClaw.entitlements."
}

# ─── Signing ─────────────────────────────────────────────────────────────
#
# Export with manual signing against freshly fetched App Store profiles.
# Xcode's cached automatic "iOS Team Store Provisioning Profile" entries can
# lag behind the current Apple Distribution certificate and make exportArchive
# fail with "doesn't include signing certificate". Downloading is read-only on
# the developer account. A profile goes INVALID when its bundle ID's
# capabilities change; fastlane's sigh used to regenerate it silently on every
# build. Here that is a separate, explicit step (`profiles --repair`) so a
# build never changes the developer account behind your back.
EXPORT_OPTIONS="$ARTIFACTS/ExportOptions.plist"

# "<bundle id><TAB><profile name>" per configured profile.
profile_entries() {
  local line
  while IFS= read -r line; do
    [[ -n "${line// /}" ]] || continue
    printf '%s\t%s\n' "${line%%=*}" "${line#*=}"
  done <<<"$PROFILES"
}

refresh_profiles() {
  local dirs=("$HOME/Library/Developer/Xcode/UserData/Provisioning Profiles")
  # iOS tooling still reads the legacy MobileDevice folder; macOS doesn't.
  [[ "$PROFILE_EXT" == "mobileprovision" ]] && dirs+=("$HOME/Library/MobileDevice/Provisioning Profiles")
  local signing_dir bundle name json id uuid file
  mkdir -p "$ARTIFACTS" "${dirs[@]}"
  # A fresh folder per run: `asc profiles download` won't overwrite a file.
  signing_dir=$(mktemp -d "$ARTIFACTS/signing.XXXXXX")
  plutil -create xml1 "$EXPORT_OPTIONS"
  /usr/libexec/PlistBuddy \
    -c "Add :method string app-store-connect" \
    -c "Add :destination string export" \
    -c "Add :signingStyle string manual" \
    -c "Add :signingCertificate string $SIGNING_CERT" \
    -c "Add :teamID string $TEAM_ID" \
    -c "Add :uploadSymbols bool true" \
    -c "Add :manageAppVersionAndBuildNumber bool false" \
    -c "Add :provisioningProfiles dict" \
    "$EXPORT_OPTIONS" >/dev/null
  if [[ -n "$INSTALLER_CERT" ]]; then
    /usr/libexec/PlistBuddy -c "Add :installerSigningCertificate string $INSTALLER_CERT" "$EXPORT_OPTIONS" >/dev/null
  fi
  while IFS=$'\t' read -r bundle name; do
    # `--name` is not an exact match: it also returns the timestamp-suffixed
    # copies `sigh --force` left behind ("<name> 1787293412"), and data[0] can
    # be one of those. The archive's PROVISIONING_PROFILE_SPECIFIER wants the
    # exact name, so match it exactly and take the newest.
    json=$(asc profiles list --name "$name" --profile-type "$PROFILE_TYPE" --profile-state ACTIVE --paginate --output json)
    id=$(NAME="$name" json_get 'max((p for p in d.get("data") or [] if p["attributes"]["name"] == __import__("os").environ["NAME"]), key=lambda p: p["attributes"].get("expirationDate") or "", default={}).get("id")' <<<"$json")
    [[ -n "$id" ]] || die "no ACTIVE $PROFILE_TYPE profile named '$name'. Run: scripts/release.sh profiles --repair"
    file="$signing_dir/$bundle.$PROFILE_EXT"
    asc profiles download --id "$id" --output "$file" >/dev/null
    require_profile_certificate "$file" "$name"  # REPO-SPECIFIC
    uuid=$(asc profiles inspect --path "$file" --output json | json_get 'd.get("uuid") or d.get("UUID")')
    [[ -n "$uuid" ]] || uuid=$(security cms -D -i "$file" | plutil -extract UUID raw -o - -)
    local d
    for d in "${dirs[@]}"; do cp "$file" "$d/$uuid.$PROFILE_EXT"; done
    /usr/libexec/PlistBuddy -c "Add :provisioningProfiles:$bundle string $uuid" "$EXPORT_OPTIONS" >/dev/null
    info "$bundle -> profile $uuid"
  done < <(profile_entries)
}

# Check (default), repair, or prune the configured profiles.
#   profiles                  read-only report
#   profiles --repair         for each profile with no ACTIVE copy: delete the
#                             INVALID one holding the name (names are unique,
#                             and an INVALID profile can't be used), then create
#                             a fresh one against the newest $DIST_CERT_TYPE cert
#   profiles --prune          also delete INVALID "<name> <timestamp>" copies
#                             that sigh --force left behind
#   --dry-run                 print the plan, change nothing
cmd_profiles() {
  local repair=false prune=false dry_run=false
  while [[ $# -gt 0 ]]; do
    case "$1" in
      --repair) repair=true ;;
      --prune) prune=true ;;
      --dry-run) dry_run=true ;;
      *) die "unknown profiles option: $1" ;;
    esac
    shift
  done
  load_credentials
  if $dry_run || ! { $repair || $prune; }; then read_only; fi
  step "$PROFILE_TYPE profiles$($repair && echo ' (repair)')$($prune && echo ' (prune)')$($dry_run && echo ' [dry run]')"
  PROFILE_LINES="$(profile_entries)" "$PYTHON" - "$PROFILE_TYPE" "$DIST_CERT_TYPE" "$repair" "$prune" "$dry_run" <<'PY'
import json, re, subprocess, sys
ptype, cert_type = sys.argv[1], sys.argv[2]
repair, prune, dry = (a == "true" for a in sys.argv[3:6])

def asc(*args):
    out = subprocess.run(["asc", *args, "--output", "json"], check=True, capture_output=True, text=True).stdout
